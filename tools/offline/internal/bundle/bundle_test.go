func TestValidatePortableRelativePath(t *testing.T) {
	for _, name := range []string{
		"site/app/index.html", "site/app/exact bytes.bin", "OpenSpecy-offline-a",
	} {
		if err := validatePortableRelativePath(name); err != nil {
			t.Errorf("valid portable path %q was rejected: %v", name, err)
		}
	}
	for _, name := range []string{
		"../escape", "site/../escape", "/absolute", "C:/absolute",
		"C:relative", `site\app\index.html`, "site//app", "./site",
		"site/app/", "site/app\nindex.html", "site/CON.txt", "site/file.",
		"site/file:name",
	} {
		if err := validatePortableRelativePath(name); err == nil {
			t.Errorf("unsafe portable path %q was accepted", name)
		}
	}
}

func TestVerifyArchiveRejectsDuplicatePortablePaths(t *testing.T) {
	for _, names := range [][]string{
		{"OpenSpecy-offline-" + testSHA + "/site/index.html",
			"OpenSpecy-offline-" + testSHA + "/site/index.html"},
		{"OpenSpecy-offline-" + testSHA + "/site/index.html",
			"OpenSpecy-offline-" + testSHA + "/site/INDEX.html"},
	} {
		archive := filepath.Join(t.TempDir(), "duplicate.zip")
		output, err := os.Create(archive)
		if err != nil {
			t.Fatal(err)
		}
		writer := zip.NewWriter(output)
		for _, name := range names {
			entry, err := writer.Create(name)
			if err != nil {
				t.Fatal(err)
			}
			if _, err := entry.Write([]byte("content")); err != nil {
				t.Fatal(err)
			}
		}
		if err := writer.Close(); err != nil {
			t.Fatal(err)
		}
		if err := output.Close(); err != nil {
			t.Fatal(err)
		}
		err = verifyArchive(archive, "OpenSpecy-offline-"+testSHA,
			testSHA, "linux-amd64", "OpenSpecy Offline")
		if err == nil || !strings.Contains(err.Error(), "duplicate or colliding") {
			t.Fatalf("expected duplicate portable path rejection, got %v", err)
		}
	}
}

func TestParseChecksumsRejectsUnsafeAndCollidingPaths(t *testing.T) {
	hash := strings.Repeat("a", 64)
	for _, content := range []string{
		hash + `  site\app\index.html` + "\n",
		hash + "  C:/index.html\n",
		hash + "  site/index.html\n" + hash + "  site/INDEX.html\n",
	} {
		if _, err := parseChecksums([]byte(content)); err == nil {
			t.Fatalf("unsafe checksum paths were accepted: %q", content)
		}
	}
}
